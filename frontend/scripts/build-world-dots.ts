/**
 * Draws the "Where I've been" map: land as a grid of dots, Natural Earth projection.
 * Writes src/features/about/places/worldDots.ts. Re-run after changing the projection or spacing:
 *
 *   node scripts/build-world-dots.ts
 *
 * Land shapes: Natural Earth 1:50m via the world-atlas package (public domain).
 */
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { geoContains, geoNaturalEarth1 } from 'd3-geo'
import { feature } from 'topojson-client'
import { D3_TRANSLATE, MAP_HEIGHT, MAP_WIDTH, SCALE } from '../src/features/about/places/projection.ts'

/** Distance between neighbouring dots, in map units (the map is MAP_WIDTH wide). */
const SPACING = 5

const require = createRequire(import.meta.url)
const topology = require('world-atlas/land-50m.json')
const land = feature(topology, topology.objects.land)
const projection = geoNaturalEarth1().scale(SCALE).translate(D3_TRANSLATE)

const rowHeight = (SPACING * Math.sqrt(3)) / 2
const dots: number[] = []
for (let row = 0, y = rowHeight / 2; y < MAP_HEIGHT; row++, y += rowHeight) {
  // Every other row is shifted by half a step: a hexagonal grid, the classic halftone look.
  for (let x = row % 2 ? SPACING : SPACING / 2; x < MAP_WIDTH; x += SPACING) {
    const position = projection.invert!([x, y])
    if (!position) continue
    // Points outside the map's outline invert to somewhere else; keep only the ones that project back.
    const [backX, backY] = projection(position)!
    if (Math.abs(backX - x) > 0.01 || Math.abs(backY - y) > 0.01) continue
    if (geoContains(land, position)) dots.push(Math.round(x * 10) / 10, Math.round(y * 10) / 10)
  }
}

const out = new URL('../src/features/about/places/worldDots.ts', import.meta.url)
writeFileSync(
  out,
  `// Generated by scripts/build-world-dots.ts; don't edit. Land from Natural Earth (public domain).\n` +
    `/** Dot centres as x, y pairs in the map's ${MAP_WIDTH}×${MAP_HEIGHT} box. */\n` +
    `export const WORLD_DOTS: readonly number[] = [${dots.join(',')}]\n\n` +
    `/** The dots' diameter that leaves a small gap between neighbours. */\n` +
    `export const DOT_SIZE = ${Math.round(SPACING * 0.62 * 10) / 10}\n`,
)
console.log(`Wrote ${dots.length / 2} dots to ${out.pathname}`)
